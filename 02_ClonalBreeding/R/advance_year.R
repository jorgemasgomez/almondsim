# Read this file from top to bottom to follow one breeding year.
# state$pop holds the living cohorts; assigning a population replaces that stage.
# state$parents holds the parents available for crossing in the current year.
# Complex prediction and OCS calculations remain in their dedicated modules.

redesign_year <- function(state, method, first_parental_use, rep,
                          record=TRUE, renew=TRUE) {
  config <- state$config
  validate_ocs_settings(config)
  if (!identical(config$design_version, 'PT_AT_ET_optiSel_adultcap32_v12')) {
    stop('Unsupported source design. Use a burn-in generated by the current implementation.')
  }
  first <- as.integer(first_parental_use)
  if (!first %in% c(9L, 6L, 4L, 2L) || (method == 'Pheno' && first < 6L)) {
    stop('Unsupported parental-use scheme.')
  }
  state$training_stage <- config$training_stage[[as.character(first)]]
  state$training_cohort_stage <- config$training_cohort_stage[[as.character(first)]]
  target <- config$parent_stage[[as.character(first)]]

  # 1. ADVANCE THE COHORTS BY ONE YEAR
  # Keep the previous populations separate: every cohort advances exactly once.
  # Assign older stages first, then replace F1 when new offspring are produced.
  previous <- state$pop
  state$pop$ET3       <- previous$ET2
  state$pop$ET2       <- previous$ET1
  state$pop$ET1       <- previous$AT3
  state$pop$AT3       <- previous$AT2
  state$pop$AT2       <- previous$AT1
  state$pop$AT1       <- previous$PT2
  state$pop$PT2       <- previous$PT1
  state$pop$PT1       <- previous$Juvenile3
  state$pop$Juvenile3 <- previous$Juvenile2
  state$pop$Juvenile2 <- previous$Seedlings
  state$pop$Seedlings <- previous$F1
  state$pop$F1        <- NULL

  state$speed_cross_trace <- NULL
  state$speed_ocs_solver <- NULL
  entrants <- 0L
  allocation <- NULL

  # 2. REPLACE THE PARENT POOL WITH LAST YEAR'S SELECTED PARENTS
  # Year-6/year-9 schemes select after evaluation and first cross next year.
  # The stored allocation can contain ordinary replacement or an OCS plan.
  if (renew && !is.null(state$pending)) {
    allocation <- state$pending
    if (allocation$use_year != state$year) {
      stop('Pending parental selection has the wrong crossing year.')
    }
    state$parents <- allocation$parents
    entrants <- allocation$new
    state$pending <- NULL
  }
  candidates <- state$pop[[target]]

  # 3. SCORE THE SEEDLINGS AND APPLY EARLY SELECTION, WHEN ENABLED
  # Use the model already available at the start of the year. If unavailable,
  # fit it from the completed archived PT cohorts, not this year's evaluations.
  start_model <- NULL
  if (method != 'Pheno') {
    if (identical(state$model_method, method)) {
      start_model <- state$prediction_pt_model
    }
    if (is.null(start_model)) {
      start_model <- redesign_fit_for_stage(state, method, 'PT2')
    }
  }

  # Accuracy describes ALL seedlings before early selection changes the cohort.
  accuracy <- NA_real_
  seedlings_before <- if (is.null(state$pop$Seedlings)) 0L else nInd(state$pop$Seedlings)
  if (seedlings_before && method != 'Pheno') {
    predicted <- redesign_predict(state$pop$Seedlings, method, start_model)
    accuracy <- suppressWarnings(cor(as.numeric(gv(predicted)), as.numeric(ebv(predicted))))
  }
  if (isTRUE(config$early_selection) && seedlings_before) {
    if (method == 'Pheno') {
      stop('Phenotypic early selection is unavailable before yield records.')
    }
    # Replace the seedling population with the retained individuals.
    state$pop$Seedlings <- redesign_choose(
      state$pop$Seedlings, min(config$seedlings_keep, seedlings_before),
      method, start_model
    )
  }

  # 4. SELECT PARENTS FOR IMMEDIATE USE IN YEAR-2/YEAR-4 SCHEMES
  # These candidates have no yield record of their own yet. Parental selection
  # uses the start-of-year predictions; OCS is handled inside redesign_allocate.
  if (renew && first < 6L && !is.null(candidates)) {
    if (any(is.finite(as.numeric(candidates@pheno)))) {
      stop('Pre-phenotyping candidates unexpectedly have yield records.')
    }
    allocation <- redesign_allocate(state, candidates, method, start_model, first, state$year)
    state$parents <- allocation$parents
    entrants <- allocation$new
  }

  # 5. CROSS THE CURRENT PARENTS AND CREATE THE NEW F1 POPULATION
  # Ordinary schemes use equal family sizes. OCS uses its validated pair plan
  # and variable family sizes; the crossing function enforces almond biology.
  ocs_solution <- if (is.null(allocation)) NULL else allocation$ocs
  options(almond.cross_state=state)
  on.exit(options(almond.cross_state=NULL), add=TRUE)
  if (is.null(ocs_solution)) {
    state$pop$F1 <- randCrossGamSI(
      list(SIPos=locuscompt_position_vector, random_failure=FALSE),
      state$parents, nCrosses=config$crosses, nProgeny=config$progeny
    )
  } else {
    state$speed_ocs_solver <- ocs_solution$solver_details
    state$pop$F1 <- randCrossGamSI(
      list(SIPos=locuscompt_position_vector, random_failure=FALSE),
      state$parents, nCrosses=NA_integer_, nProgeny=config$progeny,
      cross_plan=ocs_solution$cross_ids, family_sizes=ocs_solution$family_sizes
    )
    # Verify that generated offspring preserve the planned parental contributions.
    realized <- table(factor(
      c(state$pop$F1@mother, state$pop$F1@father), levels=state$parents@id
    )) / (2 * nInd(state$pop$F1))
    expected <- ocs_solution$contributions$contribution[
      match(names(realized), ocs_solution$contributions$id)
    ]
    if (anyNA(expected) || max(abs(as.numeric(realized) - expected)) > 1e-10) {
      stop('Realized OCS contributions differ from the validated plan.')
    }
    state$ocs_trace[[as.character(state$year)]] <- ocs_solution
  }
  state$birth[as.character(state$pop$F1@id)] <- state$year
  if (nInd(state$pop$F1) != config$crosses * config$progeny) {
    stop('Incomplete compatible progeny cohort.')
  }

  # 6. UPDATE PHENOTYPES BEFORE SELECTING TRIAL INDIVIDUALS
  # Each assignment replaces the population's aggregate evaluation. Parents
  # are evaluated separately according to age; juveniles have no yield records.
  state$pop$PT1 <- redesign_measure(state$pop$PT1, 'PT1', state)
  state$pop$PT2 <- redesign_measure(state$pop$PT2, 'PT2', state)
  state$pop$AT1 <- redesign_measure(state$pop$AT1, 'AT1', state)
  state$pop$AT2 <- redesign_measure(state$pop$AT2, 'AT2', state)
  state$pop$AT3 <- redesign_measure(state$pop$AT3, 'AT3', state)
  state$pop$ET1 <- redesign_measure(state$pop$ET1, 'ET1', state)
  state$pop$ET2 <- redesign_measure(state$pop$ET2, 'ET2', state)
  state$pop$ET3 <- redesign_measure(state$pop$ET3, 'ET3', state)
  redesign_measure_parents(state)

  # Archive the complete evaluated cohorts BEFORE discarding trial individuals.
  redesign_archive_cohorts(state)

  # 7. FIT THE MODELS FOR THIS YEAR'S COMPLETED PT AND AT COHORTS
  pt_model <- redesign_fit_for_stage(state, method, 'PT2')
  at_model <- redesign_fit_for_stage(state, method, 'AT3')
  end_model <- if (first == 9L) at_model else pt_model
  state$prediction_pt_model <- pt_model
  state$prediction_at_model <- at_model
  state$prediction_model <- pt_model
  state$model_method <- method
  state$model_training_stage <- 'PT2'

  # 8. SELECT PARENTS FOR NEXT YEAR IN YEAR-6/YEAR-9 SCHEMES
  # First use in year 6: choose from completed PT. First use in year 9: choose
  # from completed AT. Store the allocation; do not replace current parents yet.
  next_selection <- NULL
  if (renew && first >= 6L && !is.null(state$pop[[target]])) {
    if (method != 'Pheno') {
      redesign_assert_decision_training(state$pop[[target]], end_model, target)
    }
    next_selection <- redesign_allocate(
      state, state$pop[[target]], method, end_model, first, state$year
    )
    state$pending <- next_selection
  }
  state$parent_accuracy <- if (!is.null(next_selection)) next_selection$accuracy else
    if (!is.null(allocation)) allocation$accuracy else NA_real_

  # 9. REPLACE COMPLETED TRIAL COHORTS WITH THEIR SELECTED INDIVIDUALS
  # Parent recruitment above must see the whole eligible cohort, so both cuts
  # occur AFTER parental selection. Defaults retain 25 at PT and 8 at AT.
  if (!is.null(state$pop$PT2)) {
    trial_model <- if (method == 'Pheno') NULL else pt_model
    if (method != 'Pheno') {
      redesign_assert_decision_training(state$pop$PT2, trial_model, 'PT2')
    }
    state$pop$PT2 <- redesign_choose(
      state$pop$PT2, min(config$act, nInd(state$pop$PT2)), method, trial_model
    )
  }
  if (!is.null(state$pop$AT3)) {
    elite_model <- if (method == 'Pheno') NULL else at_model
    if (method != 'Pheno') {
      redesign_assert_decision_training(state$pop$AT3, elite_model, 'AT3')
    }
    state$pop$AT3 <- redesign_choose(
      state$pop$AT3, min(config$ect, nInd(state$pop$AT3)), method, elite_model
    )
  }

  # 10. SAVE THE YEAR'S OUTCOMES
  # Output formatting/audit columns live in record_results.R. No biological
  # decisions are hidden in that recording function. Fill cycles can skip it.
  if (!record) return(NULL)
  redesign_record_year(
    state, config, method, first, rep, accuracy, entrants, target,
    allocation, next_selection, ocs_solution, candidates, seedlings_before
  )
}
